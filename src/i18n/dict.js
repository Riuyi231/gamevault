  const LOCALES = { es: 'Español', en: 'English' };

  function t(locale, key, vars) {
    const lang = LOCALES[locale] ? locale : DEFAULT_LOCALE;
    let v = DICT[lang][key];
    if (v === undefined) v = DICT[DEFAULT_LOCALE][key];
    if (v === undefined) return key;
    if (Array.isArray(v)) {
      const n = vars ? Number(vars.n) : 1;
      v = v[n === 1 ? 0 : 1];
    }
    if (vars && typeof vars === 'object') {
      v = String(v).replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? String(vars[k]) : m));
    }
    return v;
  }

  return { DICT, LOCALES, t, DEFAULT_LOCALE };
